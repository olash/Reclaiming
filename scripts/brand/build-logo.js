/**
 * Builds the Reclaiming logo files (public/brand/*.svg, app/icon.svg and the
 * wordmark path used by components/logo.tsx). Text is outlined, so the files
 * work anywhere without the font installed.
 *
 *   npm i --no-save opentype.js@1.3.4 @fontsource/bricolage-grotesque@5.1.0
 *   node scripts/brand/build-logo.js
 */
const opentype = require('opentype.js');
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'public/brand');
const font = opentype.loadSync(require.resolve('@fontsource/bricolage-grotesque/files/bricolage-grotesque-latin-700-normal.woff'));

const C = { ink: '#151A3B', indigo: '#2A3586', night: '#1A2160', saffron: '#F2B035', cotton: '#F7F1E6', paper: '#FFFCF6', clay: '#B0432A' };

// ---------- Mark: the reclaiming "r" — a stem, a returning arc, and the coin it brings home.
const MARK_VB = '2.3 2.1 48 48';
function markInner(stem, coin, ring) {
  return `<path d="M13.5 39.5V25c0-7.6 5-12.2 12.6-12.2" fill="none" stroke="${stem}" stroke-width="9" stroke-linecap="round"/>` +
    `<circle cx="36.2" cy="15.6" r="7.4" fill="${coin}"/>` + (ring ? `<circle cx="37" cy="12" r="2.2" fill="none" stroke="${ring}" stroke-width="1.4" opacity=".55"/>` : '');
}
const svg = (vb, body, title) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" role="img"><title>${title}</title>${body}</svg>\n`;

fs.writeFileSync(`${OUT}/mark.svg`, svg(MARK_VB, markInner(C.indigo, C.saffron), 'Reclaiming mark'));
fs.writeFileSync(`${OUT}/mark-ink.svg`, svg(MARK_VB, markInner(C.ink, C.ink), 'Reclaiming mark, one colour'));
fs.writeFileSync(`${OUT}/mark-reversed.svg`, svg(MARK_VB, `<rect x="2.3" y="2.1" width="48" height="48" fill="${C.night}"/>` + markInner(C.cotton, C.saffron), 'Reclaiming mark on indigo'));
const icon = `<rect width="48" height="48" rx="12" fill="${C.night}"/><g transform="translate(1.4 1.6) scale(.86)">${markInner(C.cotton, C.saffron)}</g>`;
fs.writeFileSync(`${OUT}/app-icon.svg`, svg('0 0 48 48', icon, 'Reclaiming app icon'));
fs.writeFileSync(path.join(ROOT, 'app/icon.svg'), svg('0 0 48 48', icon, 'Reclaiming'));

// ---------- Wordmark: "reclaıming", with the saffron coin as the dot of the first i.
const SIZE = 100;
const text = 'reclaıming'; // first i dotless (the coin dots it), second i ordinary
const glyphs = font.stringToGlyphs(text);
let x = 0; const parts = []; let dot = null;
const scale = SIZE / font.unitsPerEm;
const tracking = -0.035 * SIZE;
const iGlyph = font.charToGlyph('i');
const ib = iGlyph.getBoundingBox();
const xh = font.charToGlyph('x').getBoundingBox().y2;
glyphs.forEach((g, idx) => {
  const p = g.getPath(x, 0, SIZE);
  parts.push(p.toPathData(2));
  if (text[idx] === 'ı') {
    const b = g.getBoundingBox();
    const cx = x + ((b.x1 + b.x2) / 2) * scale;
    const top = ib.y2 * scale, low = xh * scale;
    const r = (top - low) * 0.5;
    dot = { cx, cy: -(low + r + 0.045 * SIZE), r };
  }
  x += g.advanceWidth * scale + tracking;
});
const width = x - tracking;
const asc = 0.80 * SIZE, desc = 0.22 * SIZE;
const vb = `0 ${-asc} ${width.toFixed(1)} ${(asc + desc).toFixed(1)}`;
const wm = (ink, coin) => `<path d="${parts.join('')}" fill="${ink}"/><circle cx="${dot.cx.toFixed(2)}" cy="${dot.cy.toFixed(2)}" r="${dot.r.toFixed(2)}" fill="${coin}"/>`;
fs.writeFileSync(`${OUT}/wordmark.svg`, svg(vb, wm(C.ink, C.saffron), 'Reclaiming'));
fs.writeFileSync(`${OUT}/wordmark-reversed.svg`, svg(vb, wm(C.cotton, C.saffron), 'Reclaiming'));

// ---------- Horizontal lockup: mark + wordmark, mark height = 1.0 cap-ish.
const markH = 1.0 * SIZE; const gap = 0.24 * SIZE; const mScale = markH / 48;
const lock = (stem, coin, ink) => `<g transform="translate(0 ${-asc + 0.02 * SIZE}) scale(${mScale})">${markInner(stem, coin)}</g><g transform="translate(${markH + gap} 0)">${wm(ink, coin)}</g>`;
const lvb = `0 ${-asc} ${(markH + gap + width).toFixed(1)} ${(asc + desc).toFixed(1)}`;
fs.writeFileSync(`${OUT}/lockup.svg`, svg(lvb, lock(C.indigo, C.saffron, C.ink), 'Reclaiming'));
fs.writeFileSync(`${OUT}/lockup-reversed.svg`, svg(lvb, lock(C.cotton, C.saffron, C.cotton), 'Reclaiming'));

// Export geometry for the React component.
fs.writeFileSync(path.join(ROOT, 'components/brand/wordmark-path.ts'),
  `// Generated by scripts/brand/build-logo.js from Bricolage Grotesque Bold (outlined).\n// The wordmark is "reclaıming": the first i is dotless and the saffron coin is its dot.\nexport const WORDMARK = ${JSON.stringify({ d: parts.join(''), dot: { cx: +dot.cx.toFixed(2), cy: +dot.cy.toFixed(2), r: +dot.r.toFixed(2) }, viewBox: vb })} as const;\n`);
console.log('wordmark width', width.toFixed(1), 'dot', dot);
